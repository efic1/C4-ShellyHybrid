local H = require("tests.harness")
local F = require("tests.fakes")
local AB = require("hub.addressbook")
local test, eq, truthy, falsy = H.test, H.eq, H.truthy, H.falsy

local function new()
  local rt = F.new()
  local tr, downs = {}, {}
  local ab = AB.new(rt, { onTransition = function(id, f, t) tr[#tr + 1] = f .. ">" .. t end, onDown = function(id) downs[#downs + 1] = id end })
  return rt, ab, tr, downs
end

test("addressbook: setting an address starts Probing; the same address again changes nothing", function()
  local rt, ab, tr = new()
  truthy(ab:setAddress("d", "192.168.1.5", "cloud"))
  eq(ab:get("d").lan, "Probing")
  falsy(ab:setAddress("d", "192.168.1.5", "cloud"))
  falsy(ab:setAddress("d", "garbage", "cloud"))
  eq(tr, { "NoAddress>Probing" })
end)

test("addressbook: Up -> Degraded (x2) -> Down on the third consecutive failure, then back-off 15/30/60/300s", function()
  local rt, ab, tr, downs = new()
  ab:setAddress("d", "192.168.1.5", "cloud"); ab:noteSuccess("d")
  ab:noteFailure("d", "t"); eq(ab:get("d").lan, "Degraded")
  ab:noteFailure("d", "t"); eq(ab:get("d").lan, "Degraded")
  ab:noteFailure("d", "t"); eq(ab:get("d").lan, "Down"); eq(downs, { "d" })
  local start = rt.clock.now()
  eq(ab:get("d").nextProbeAt - start, 15000)
  falsy(ab:probeDue("d")); rt.advance(15000); truthy(ab:probeDue("d"))
  local expect = { 30000, 60000, 300000, 300000 }
  for _, e in ipairs(expect) do
    local t = rt.clock.now()
    ab:noteFailure("d", "probe")
    eq(ab:get("d").nextProbeAt - t, e)
  end
end)

test("addressbook: any success clears the failure count and back-off", function()
  local rt, ab = new()
  ab:setAddress("d", "192.168.1.5", "cloud")
  ab:noteFailure("d", "x"); ab:noteFailure("d", "x")
  eq(ab:get("d").lan, "Down")
  ab:noteSuccess("d")
  local d = ab:get("d")
  eq(d.lan, "Up"); eq(d.failures, 0); eq(d.backoffIdx, 0)
end)

test("addressbook: a failed probe of a Probing device goes straight to Down", function()
  local rt, ab = new()
  ab:setAddress("d", "192.168.1.5", "cloud")
  ab:noteFailure("d", "no answer")
  eq(ab:get("d").lan, "Down")
end)

test("addressbook: lanUsable covers Up/Degraded/Probing only", function()
  local rt, ab = new()
  falsy(ab:lanUsable("d"))
  ab:setAddress("d", "192.168.1.5", "cloud"); truthy(ab:lanUsable("d"))
  ab:noteSuccess("d"); truthy(ab:lanUsable("d"))
  ab:noteFailure("d", "x"); truthy(ab:lanUsable("d"))
  ab:noteFailure("d", "x"); ab:noteFailure("d", "x"); falsy(ab:lanUsable("d"))
  ab:noteSuccess("d"); ab:noteAuthReject("d", "h"); falsy(ab:lanUsable("d"))
end)

test("addressbook: an override always wins; the cloud value is ignored and warned about once", function()
  local rt, ab = new()
  truthy(ab:setAddress("d", "10.0.0.9", "override"))
  falsy(ab:setAddress("d", "192.168.1.5", "cloud"))
  falsy(ab:setAddress("d", "192.168.1.6", "cloud"))
  eq(ab:get("d").address, "10.0.0.9")
  local n = 0
  for _, l in ipairs(rt.lines) do if l:find("override", 1, true) then n = n + 1 end end
  eq(n, 1, "warned once")
  ab:clearOverride("d")
  truthy(ab:setAddress("d", "192.168.1.5", "cloud"))
end)

test("addressbook: identity mismatch discards a cloud address and reports the device down", function()
  local rt, ab, tr, downs = new()
  ab:setAddress("d", "192.168.1.5", "cloud"); ab:noteSuccess("d"); ab:noteIdentityOk("d")
  ab:noteIdentityMismatch("d", { mac = "OTHER" })
  local d = ab:get("d")
  eq(d.address, nil); eq(d.lan, "NoAddress"); eq(d.lastIdentityOk, nil); eq(downs, { "d" })
end)

test("addressbook: identity mismatch on an OVERRIDE keeps the override but goes Down", function()
  local rt, ab = new()
  ab:setAddress("d", "10.0.0.9", "override"); ab:noteSuccess("d")
  ab:noteIdentityMismatch("d", { mac = "OTHER" })
  eq(ab:get("d").address, "10.0.0.9"); eq(ab:get("d").lan, "Down")
end)

test("addressbook: AuthStop is left only by clearAuthStop, which resumes at Probing", function()
  local rt, ab = new()
  ab:setAddress("d", "192.168.1.5", "cloud"); ab:noteSuccess("d")
  ab:noteAuthReject("d", "hash")
  eq(ab:get("d").lan, "AuthStop")
  ab:noteSuccess("d"); eq(ab:get("d").lan, "AuthStop", "a success elsewhere must not clear an auth stop")
  ab:noteFailure("d", "x"); eq(ab:get("d").lan, "AuthStop")
  falsy(ab:probeDue("d"))
  ab:clearAuthStop("d"); eq(ab:get("d").lan, "Probing"); eq(ab:get("d").authStopHash, nil)
end)

test("addressbook: route(): LAN when usable, Cloud when the cloud is ok and not known offline, else Unreachable", function()
  local rt, ab = new()
  ab:setAddress("d", "192.168.1.5", "cloud"); ab:noteSuccess("d")
  eq(ab:route("d", true), "LAN"); eq(ab:route("d", false), "LAN")
  ab:noteFailure("d", "x"); ab:noteFailure("d", "x"); ab:noteFailure("d", "x")
  eq(ab:route("d", true), "Cloud"); eq(ab:route("d", false), "Unreachable")
  ab:setCloudOnline("d", false)
  eq(ab:route("d", true), "Unreachable")
  eq(ab:route("unknown", true), "Cloud")
end)

test("addressbook: export/import restores addresses as Probing (never trusted Up) and keeps an auth stop", function()
  local rt, ab = new()
  ab:setAddress("a", "192.168.1.5", "cloud"); ab:noteSuccess("a"); ab:setIdentity("a", { mac = "AA" })
  ab:setAddress("b", "192.168.1.6", "cloud"); ab:noteAuthReject("b", "hash-b")
  local data = ab:export()
  local rt2, ab2 = new()
  ab2:import(data)
  eq(ab2:get("a").address, "192.168.1.5"); eq(ab2:get("a").lan, "Probing"); eq(ab2:get("a").identity, { mac = "AA" })
  eq(ab2:get("b").lan, "AuthStop"); eq(ab2:get("b").authStopHash, "hash-b")
  truthy(ab2:lanUsable("a"))
end)

test("addressbook: counts summarise states for the LAN Status property", function()
  local rt, ab = new()
  ab:setAddress("a", "192.168.1.5", "cloud"); ab:noteSuccess("a")
  ab:setAddress("b", "192.168.1.6", "cloud"); ab:noteFailure("b", "x")
  ab:ensure("c")
  local c = ab:counts()
  eq(c.Up, 1); eq(c.Down, 1); eq(c.NoAddress, 1)
end)
