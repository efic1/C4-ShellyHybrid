local H = require("tests.harness")
local F = require("tests.fakes")
local Auth = require("hub.transport.lan_auth")
local test, eq, truthy, falsy, contains, not_contains = H.test, H.eq, H.truthy, H.falsy, H.contains, H.not_contains

test("auth: digest response matches an independent RFC 7616 SHA-256 computation", function()
  local rt = F.new()
  local a = Auth.new(rt)
  a:setChallenge("dev", { realm = "shellyplus1pm-b48a0a1cd978", nonce = "abc123nonce", qop = "auth", algorithm = "SHA-256" })
  local h = a:header("dev", "POST", "/rpc/Switch.Set", "admin", "secret-pass", "0a1b2c3d")
  contains(h, 'response="f363d8349f1449d7bf1dbc26ca2f434be1b266ddb7cba33b79057803cbae4251"')
  contains(h, "nc=00000001"); contains(h, 'cnonce="0a1b2c3d"'); contains(h, 'uri="/rpc/Switch.Set"'); contains(h, "algorithm=SHA-256")
  local h2 = a:header("dev", "POST", "/rpc/Switch.Set", "admin", "secret-pass", "0a1b2c3d")
  contains(h2, "nc=00000002")
end)

test("auth: challenge parsing (quoted and bare values) and unsupported algorithms", function()
  local ch = Auth.parseChallenge('Digest qop="auth", realm="shellypro4pm-f008d1d8b8b8", nonce="AAAAAABn", algorithm=SHA-256')
  eq(ch.realm, "shellypro4pm-f008d1d8b8b8"); eq(ch.nonce, "AAAAAABn"); eq(ch.qop, "auth")
  local bad, why = Auth.parseChallenge('Digest realm="x", nonce="y", algorithm=MD5')
  eq(bad, nil); contains(why, "unsupported digest algorithm")
  eq(Auth.parseChallenge("Basic realm=x"), nil)
  eq(Auth.parseChallenge(nil), nil)
  eq(Auth.parseChallenge('Digest realm="x"'), nil)
end)

test("auth: a stop is bound to the FAILED password: a different password is allowed, the same one is not", function()
  local rt = F.new()
  local a = Auth.new(rt)
  a:stop("dev", "wrong-pass")
  truthy(a:isStopped("dev", "wrong-pass"))
  falsy(a:isStopped("dev", "new-pass"), "changing the password lifts the stop")
  falsy(a:isStopped("other", "wrong-pass"))
  a:clear("dev")
  falsy(a:isStopped("dev", "wrong-pass"))
end)

test("auth: the stop marker stores a hash, never the password", function()
  local rt = F.new()
  local a = Auth.new(rt)
  a:stop("dev", "correct horse battery")
  not_contains(a:stopHash("dev"), "correct")
  local b = Auth.new(rt)
  b:restoreStop("dev", a:stopHash("dev"))
  truthy(b:isStopped("dev", "correct horse battery"))
end)
