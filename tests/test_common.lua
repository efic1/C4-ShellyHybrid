local H = require("tests.harness")
local U = require("common.util")
local Log = require("common.log")
local SetProp = require("common.setprop")
local test, eq, truthy, falsy, contains, not_contains = H.test, H.eq, H.truthy, H.falsy, H.contains, H.not_contains

test("util: flat_eq / normalize_mac / is_ipv4 / norm_id", function()
  truthy(U.flat_eq({ a = 1, b = 2 }, { b = 2, a = 1 }))
  falsy(U.flat_eq({ a = 1 }, { a = 1, b = 2 }))
  falsy(U.flat_eq({ a = 1 }, { a = 2 }))
  eq(U.normalize_mac("b4:8a:0a:1c:d9:78"), "B48A0A1CD978")
  eq(U.normalize_mac("nonsense"), nil)
  truthy(U.is_ipv4("192.168.1.40"))
  falsy(U.is_ipv4("300.1.1.1"))
  falsy(U.is_ipv4("0.0.0.0"))
  falsy(U.is_ipv4("not-an-ip"))
  eq(U.norm_id("B4-8A-0A:1C D9 78"), "b48a0a1cd978")
end)

test("log: levels gate output and skip formatting work below the level", function()
  local lines = {}
  local log = Log.new({ level = "Info", sink = function(l) lines[#lines + 1] = l end })
  local called = false
  local mt = setmetatable({}, { __tostring = function() called = true return "x" end })
  log:debug("value %s", mt)
  falsy(called, "debug arguments must not be formatted at Info level")
  eq(#lines, 0)
  log:info("hello %d", 5)
  eq(#lines, 1)
  contains(lines[1], "INFO: hello 5")
  log:setLevel("Error")
  log:info("hidden")
  eq(#lines, 1)
end)

test("log: secrets, auth_key and digest headers are redacted everywhere", function()
  local lines = {}
  local log = Log.new({ level = "Debug", sink = function(l) lines[#lines + 1] = l end })
  log:setSecret("cloudKey", "SuperSecretKey123")
  log:setSecret("devPass", "hunter2hunter2")
  log:info("url https://x/v2?auth_key=SuperSecretKey123&id=1 pass=hunter2hunter2")
  log:info('Authorization: Digest username="admin", response="abcdef"')
  log:info('response="deadbeef" tail')
  log:block({ "block line with hunter2hunter2" })
  local all = table.concat(lines, "\n")
  not_contains(all, "SuperSecretKey123")
  not_contains(all, "hunter2hunter2")
  not_contains(all, "abcdef")
  not_contains(all, "deadbeef")
  contains(all, "auth_key=******")
end)

test("log: clearing a secret stops scrubbing; short values are ignored", function()
  local log = Log.new({ level = "Debug", sink = function() end })
  log:setSecret("k", "abc")
  eq(log:redact("abc"), "abc")
  log:setSecret("k", "abcdefgh")
  eq(log:redact("xx abcdefgh"), "xx ******")
  log:setSecret("k", nil)
  eq(log:redact("xx abcdefgh"), "xx abcdefgh")
end)

test("log: ring keeps the newest entries, newest first, and block() does not enter it", function()
  local t = 0
  local log = Log.new({ level = "Info", ringMax = 3, sink = function() end, clock = function() t = t + 1000 return t end })
  for i = 1, 5 do log:info("e%d", i) end
  log:block({ "not recorded" })
  local r = log:recent()
  eq(#r, 3)
  contains(r[1], "e5"); contains(r[3], "e3")
  local txt = log:recentText(2)
  contains(txt, "e5"); contains(txt, "e4"); not_contains(txt, "e3")
end)

test("log: debug lines are not recorded in the activity ring", function()
  local log = Log.new({ level = "Debug", sink = function() end })
  log:debug("noise"); log:info("signal")
  eq(#log:recent(), 1)
end)

test("setprop: unchanged values do not reach Director", function()
  local n, last = 0, {}
  local sp = SetProp.new(function(k, v) n = n + 1; last[k] = v end)
  truthy(sp.set("A", "1")); falsy(sp.set("A", 1)); falsy(sp.set("A", "1"))
  truthy(sp.set("A", "2"))
  eq(n, 2); eq(last.A, "2")
  sp.forget("A")
  truthy(sp.set("A", "2"))
  eq(sp.writes(), 3)
end)
