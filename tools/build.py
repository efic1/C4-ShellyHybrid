#!/usr/bin/env python3
"""Generate driver.xml + ids.lua, bundle Lua modules, render documentation, package .c4z files.

  python3 tools/build.py            # build everything into build/
  python3 tools/build.py --check    # fail if committed generated files are stale
"""
import os, re, sys, zipfile, html, json
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import spec  # noqa: E402

SRC = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, "build")

COMMON_MODS = ["common.util", "common.log", "common.setprop", "common.sched", "common.ids", "common.protocol", "common.runtime"]
HUB_MODS = COMMON_MODS + ["common.persist", "hub.transport.parse", "hub.transport.cloudqueue", "hub.transport.cloud",
                          "hub.transport.lan_auth", "hub.transport.lan_gen1", "hub.transport.lan", "hub.transport.lan_dispatch",
                          "hub.addressbook", "hub.registry", "hub.router", "hub.feed.lan_poll", "hub.feed.cloud_check", "hub.core"]
CHILD_MODS = COMMON_MODS + ["common.childcore"]


def modules_for(key):
    if key == "hub":
        return HUB_MODS
    return CHILD_MODS + [key + ".proxyglue"]


# ------------------------------------------------------------------------------------------- ids.lua
def gen_ids_lua():
    def ev(lst):
        return ",\n".join('    { id = %d, name = "%s" }' % (i, n) for i, n, _ in lst)
    lines = ["-- GENERATED by tools/build.py from tools/spec.py. DO NOT EDIT.", "local M = {}", "",
             "M.VERSION = %s" % json.dumps(spec.VERSION), "M.BINDING = %d" % spec.BINDING, "",
             "M.protocol = {"]
    for k, v in spec.PROTOCOL.items():
        lines.append('  %s = "%s",' % (k, v))
    lines += ["}", "", "M.events = {", "  child = {", ev(spec.CHILD_EVENTS), "  },", "  relay = {", ev(spec.RELAY_EVENTS), "  },",
              "  hub = {", ev(spec.HUB_EVENTS), "  },", "}", "", "M.variables = {", "  child = {"]
    lines += ['    { name = "%s", type = "%s" },' % v for v in spec.CHILD_VARIABLES]
    lines += ["  },", "  relay = {"]
    lines += ['    { name = "%s", type = "%s" },' % v for v in spec.RELAY_VARIABLES]
    lines += ["  },", "  contact = {"]
    lines += ['    { name = "%s", type = "%s" },' % v for v in spec.CONTACT_VARIABLES]
    lines += ["  },", "  sensor = {"]
    lines += ['    { name = "%s", type = "%s" },' % v for v in spec.SENSOR_VARIABLES]
    lines += ["  },", "}", ""]
    # Composer delivers an action as ExecuteCommand("LUA_ACTION", {ACTION = ...}). Two of the author's own drivers disagree on whether
    # ACTION carries the action's <name> or its <command>, so both are accepted (see common/protocol.lua resolveAction).
    lines.append("M.actions = {")
    for group, lst in (("hub", spec.HUB_ACTIONS), ("child", spec.CHILD_ACTIONS)):
        lines.append("  %s = {" % group)
        for label, cmd in lst:
            lines.append('    { label = %s, cmd = "%s" },' % (json.dumps(label), cmd))
        lines.append("  },")
    lines += ["}", "", "return M", ""]
    return "\n".join(lines)


# ---------------------------------------------------------------------------------------- driver.xml
def gen_xml(key, d):
    o = []
    a = o.append
    a('<devicedata>')
    a('  <copyright>Copyright 2026 %s</copyright>' % spec.CREATOR)
    a('  <creator>%s</creator>' % spec.CREATOR)
    a('  <manufacturer>%s</manufacturer>' % escape(spec.MANUFACTURER))
    a('  <name>%s</name>' % escape(d["name"]))
    a('  <model>%s</model>' % escape(d["model"]))
    a('  <created>2026-09-30 00:00</created>')
    a('  <modified>2026-09-30 00:00</modified>')
    a('  <version>%s</version>' % spec.VERSION)
    a('  <small>devices_sm\\C4.gif</small>')
    a('  <large>devices_lg\\C4.gif</large>')
    a('  <control>lua_gen</control>')
    a('  <controlmethod>ip</controlmethod>')
    a('  <driver>DriverWorks</driver>')
    if d["proxy"]:
        a('  <proxies qty="1">')
        a('    <proxy proxybindingid="%d" name="%s" primary="True">%s</proxy>' % (spec.BINDING, escape(d["proxy"][1]), d["proxy"][0]))
        a('  </proxies>')
    if d.get("category"):
        a('  <composer_categories><category>%s</category></composer_categories>' % escape(d["category"]))
    if d["caps"]:
        a('  <capabilities>')
        for k, v in d["caps"].items():
            a('    <%s>%s</%s>' % (k, v, k))
        a('  </capabilities>')
    a('  <events>')
    for i, n, desc in d["events"]:
        a('    <event><id>%d</id><name>%s</name><description>%s</description></event>' % (i, escape(n), escape(desc)))
    a('  </events>')
    a('  <config>')
    a('    <power_management_method>AlwaysOn</power_management_method>')
    a('    <power_command_delay>0</power_command_delay>')
    a('    <power_delay>0</power_delay>')
    a('    <power_command_needed>False</power_command_needed>')
    a('    <documentation file="www/documentation.html"/>')
    a('    <script file="driver.lua"/>')
    a('    <properties>')
    for p in d["props"]:
        a('      <property>')
        a('        <name>%s</name>' % escape(p["name"]))
        a('        <type>%s</type>' % p["type"])
        a('        <readonly>%s</readonly>' % ("true" if p["readonly"] else "false"))
        a('        <default>%s</default>' % escape(p["default"]))
        if p["type"] == "RANGED_INTEGER":
            a('        <minimum>%d</minimum>' % p["min"])
            a('        <maximum>%d</maximum>' % p["max"])
        if p["type"] == "LIST":
            a('        <items>')
            for it in p["items"]:
                a('          <item>%s</item>' % escape(it))
            a('        </items>')
        a('      </property>')
    a('    </properties>')
    a('    <actions>')
    for label, cmd in d["actions"]:
        a('      <action><name>%s</name><command>%s</command></action>' % (escape(label), cmd))
    a('    </actions>')
    a('  </config>')
    if d["connections"]:
        a('  <connections>')
        for c in d["connections"]:
            a('    <connection>')
            a('      <id>%d</id>' % c["id"])
            a('      <facing>6</facing>')
            a('      <connectionname>%s</connectionname>' % escape(c["name"]))
            a('      <type>%d</type>' % c.get("type", 1))
            a('      <consumer>False</consumer>')
            a('      <audiosource>False</audiosource>')
            a('      <videosource>False</videosource>')
            a('      <linelevel>False</linelevel>')
            a('      <classes><class><classname>%s</classname></class></classes>' % c["cls"])
            a('    </connection>')
        a('  </connections>')
    a('</devicedata>')
    return "\n".join(o) + "\n"


# --------------------------------------------------------------------------------------------- bundle
def read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def bundle(key, d):
    mods = modules_for(key)
    out = ["-- %s v%s -- GENERATED by tools/build.py from src/. DO NOT EDIT THIS FILE." % (d["name"], spec.VERSION),
           "-- Modules are embedded and resolved by a private require(), so nothing depends on Control4's",
           "-- module search path or on other files in the .c4z.",
           "local __src, __loaded = {}, {}",
           "local function require(name)",
           "  local m = __loaded[name]",
           "  if m ~= nil then return m end",
           "  local f = __src[name]",
           "  if not f then error('module not found: ' .. tostring(name), 2) end",
           "  m = f(name)",
           "  if m == nil then m = true end",
           "  __loaded[name] = m",
           "  return m",
           "end", ""]
    for m in mods:
        path = os.path.join(SRC, *m.split(".")) + ".lua"
        out.append("__src[%s] = function(...)" % json.dumps(m))
        out.append(read(path).rstrip())
        out.append("end")
        out.append("")
    out.append("-- ---- driver entry points ----")
    out.append(read(os.path.join(SRC, d["dir"], "driver.lua")).rstrip())
    out.append("")
    return "\n".join(out)


# ------------------------------------------------------------------------------------------------ docs
def md_to_html(md):
    try:
        import markdown
        return markdown.markdown(md, extensions=["tables", "fenced_code"])
    except Exception:
        pass
    out, in_code, in_list = [], False, False
    for line in md.split("\n"):
        if line.startswith("```"):
            out.append("</pre>" if in_code else "<pre>")
            in_code = not in_code
            continue
        if in_code:
            out.append(html.escape(line))
            continue
        m = re.match(r"^(#{1,4})\s+(.*)$", line)
        if m:
            if in_list:
                out.append("</ul>"); in_list = False
            n = len(m.group(1))
            out.append("<h%d>%s</h%d>" % (n, html.escape(m.group(2)), n))
        elif re.match(r"^\s*[-*]\s+", line):
            if not in_list:
                out.append("<ul>"); in_list = True
            item = html.escape(re.sub(r"^\s*[-*]\s+", "", line))
            item = re.sub(r"`([^`]+)`", r"<code>\1</code>", item)
            out.append("<li>%s</li>" % item)
        elif line.strip() == "":
            if in_list:
                out.append("</ul>"); in_list = False
            out.append("")
        else:
            t = html.escape(line)
            t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
            t = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", t)
            out.append("<p>%s</p>" % t)
    if in_list:
        out.append("</ul>")
    return "\n".join(out)


def doc_html(key, d):
    guide = read(os.path.join(ROOT, "docs", "COMPOSER-GUIDE.md")) if os.path.exists(os.path.join(ROOT, "docs", "COMPOSER-GUIDE.md")) else "# %s" % d["name"]
    body = md_to_html(guide)
    return ("<!DOCTYPE html><html><head><meta charset=\"utf-8\"><title>%s</title>"
            "<style>body{font-family:sans-serif;max-width:52em;margin:1em auto;line-height:1.4}code,pre{background:#eee}"
            "pre{padding:.5em;overflow:auto}table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:.2em .5em}</style>"
            "</head><body><p><i>%s v%s</i></p>%s</body></html>") % (escape(d["name"]), escape(d["name"]), spec.VERSION, body)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    check = "--check" in sys.argv
    quiet = "--quiet" in sys.argv
    ids_path = os.path.join(SRC, "common", "ids.lua")
    ids = gen_ids_lua()
    if check:
        if not os.path.exists(ids_path) or read(ids_path) != ids:
            print("STALE: src/common/ids.lua is out of date; run tools/build.py")
            sys.exit(1)
        print("generated files are current")
        return
    write(ids_path, ids)
    for key, d in spec.DRIVERS.items():
        base = os.path.join(OUT, d["file"])
        write(os.path.join(base, "driver.xml"), gen_xml(key, d))
        write(os.path.join(base, "driver.lua"), bundle(key, d))
        write(os.path.join(base, "www", "documentation.html"), doc_html(key, d))
        c4z = os.path.join(OUT, d["file"] + ".c4z")
        with zipfile.ZipFile(c4z, "w", zipfile.ZIP_DEFLATED) as z:
            for rel in ("driver.xml", "driver.lua", "www/documentation.html"):
                z.write(os.path.join(base, *rel.split("/")), rel)
        if not quiet:
            print("built %-22s %6d bytes" % (d["file"] + ".c4z", os.path.getsize(c4z)))


if __name__ == "__main__":
    main()
